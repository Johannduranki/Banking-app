CREATE TABLE IF NOT EXISTS kyc_policies (
  id CHAR(36) PRIMARY KEY,
  code VARCHAR(80) NOT NULL,
  version INT UNSIGNED NOT NULL,
  name VARCHAR(160) NOT NULL,
  status ENUM('DRAFT','ACTIVE','RETIRED') NOT NULL DEFAULT 'DRAFT',
  description TEXT NULL,
  effective_from DATETIME(3) NULL,
  effective_to DATETIME(3) NULL,
  created_by CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE INDEX uk_kyc_policy_code_version (code,version),
  INDEX idx_kyc_policy_status_effective (status,effective_from,effective_to),
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS kyc_policy_levels (
  id CHAR(36) PRIMARY KEY,
  policy_id CHAR(36) NOT NULL,
  kyc_level ENUM('LEVEL_0','LEVEL_1','LEVEL_2','LEVEL_3') NOT NULL,
  requires_manual_approval BOOLEAN NOT NULL DEFAULT FALSE,
  description TEXT NULL,
  UNIQUE INDEX uk_kyc_policy_level (policy_id,kyc_level),
  FOREIGN KEY (policy_id) REFERENCES kyc_policies(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS kyc_policy_requirements (
  id CHAR(36) PRIMARY KEY,
  policy_level_id CHAR(36) NOT NULL,
  evidence_type ENUM('NATIONAL_ID_DOCUMENT','PASSPORT','ALTERNATIVE_IDENTITY_DOCUMENT','CUSTOMER_PERSONAL_INFORMATION','CUSTOMER_INFORMATION_VERIFIED','VERIFIED_MOBILE','SELFIE','FACIAL_BIOMETRIC','LIVENESS','FINGERPRINT','ADDRESS_EVIDENCE','BRANCH_ASSISTED_VERIFICATION','COMPLIANCE_OFFICER_VERIFICATION','ENHANCED_DUE_DILIGENCE') NOT NULL,
  requirement_mode ENUM('REQUIRED','ONE_OF','OPTIONAL') NOT NULL,
  group_code VARCHAR(80) NULL,
  minimum_count TINYINT UNSIGNED NOT NULL DEFAULT 1,
  configuration_json JSON NULL,
  display_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  INDEX idx_kyc_requirement_level_order (policy_level_id,display_order),
  FOREIGN KEY (policy_level_id) REFERENCES kyc_policy_levels(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS kyc_workflow_evaluations (
  id CHAR(36) PRIMARY KEY,
  case_id CHAR(36) NOT NULL,
  policy_id CHAR(36) NOT NULL,
  kyc_level ENUM('LEVEL_0','LEVEL_1','LEVEL_2','LEVEL_3') NOT NULL,
  eligible BOOLEAN NOT NULL,
  evidence_snapshot_json JSON NOT NULL,
  requirement_results_json JSON NOT NULL,
  missing_requirements_json JSON NOT NULL,
  evaluated_by CHAR(36) NULL,
  evaluated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_kyc_evaluation_case_time (case_id,evaluated_at),
  FOREIGN KEY (case_id) REFERENCES kyc_cases(id) ON DELETE CASCADE,
  FOREIGN KEY (policy_id) REFERENCES kyc_policies(id) ON DELETE RESTRICT,
  FOREIGN KEY (evaluated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

